"""Build the wiki's navigation from the front matter of the content pages.

Content pages are the *.md files at the repository root that have a
`category:` in their front matter. From them this script writes:

- _Sidebar.md                 every page, grouped by category
- Category-<Name>.md          one index page per category
- Tags.md, Tag-<tag>.md       the tag index and one page per tag
- README.md (Home)            the block between INDEX:START and INDEX:END
- in each content page        the breadcrumb between NAV:START and NAV:END,
                              and the glossary terms used on the page
                              between SEEALSO:START and SEEALSO:END

Then it checks that every relative link (and #anchor) resolves, and exits 1
if one does not. Run it after adding a page or changing front matter:

    python3 scripts/build_wiki.py
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HOME = "README.md"
GLOSSARY = "Glossary.md"
GENERATED_NOTE = "<!-- Generated by scripts/build_wiki.py from page front matter. Do not edit by hand. -->"
# Order in which categories appear; categories not listed here follow alphabetically.
CATEGORY_ORDER = ["Foundations", "Agents", "Models and providers", "Security and data", "How-to", "Problems & solutions"]


def front_matter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    meta = {}
    if not m:
        return meta
    for line in m.group(1).splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            value = [v.strip().strip('"') for v in value[1:-1].split(",") if v.strip()]
        else:
            value = value.strip('"')
        meta[key.strip()] = value
    return meta


def slug(text):
    """GitHub-style heading anchor."""
    s = text.strip().lower()
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def file_slug(name):
    return re.sub(r"[^A-Za-z0-9]+", "-", name).strip("-")


def cat_file(cat):
    return f"Category-{file_slug(cat)}.md"


def tag_file(tag):
    return f"Tag-{file_slug(tag)}.md"


def replace_block(text, name, content):
    start, end = f"<!-- {name}:START -->", f"<!-- {name}:END -->"
    if start not in text:
        return text
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{start}\n{content}\n{end}{tail}"


def sorted_cats(cats):
    known = [c for c in CATEGORY_ORDER if c in cats]
    return known + sorted(c for c in cats if c not in CATEGORY_ORDER)


def glossary_terms():
    """(display name, anchor, regex) for each glossary heading."""
    text = (ROOT / GLOSSARY).read_text(encoding="utf-8")
    terms = []
    for heading in re.findall(r"^### (.+)$", text, re.M):
        names = [re.sub(r"\s*\(.*\)", "", heading).strip()]
        names += re.findall(r"\(([^)]+)\)", heading)
        patterns = []
        for n in names:
            if n.isupper() or any(ch.isdigit() for ch in n):  # acronyms: exact case
                patterns.append(rf"(?<![\w-]){re.escape(n)}s?(?![\w-])")
            else:
                patterns.append(rf"(?i)(?<![\w-]){re.escape(n)}s?(?![\w-])")
        terms.append((heading, slug(heading), patterns))
    return terms


def body_for_terms(text):
    """Page text without front matter, generated blocks, code, links' URLs, sources and footer."""
    text = re.sub(r"^---\n.*?\n---\n", "", text, flags=re.S)
    text = re.sub(r"<!-- (\w+):START -->.*?<!-- \1:END -->", "", text, flags=re.S)
    text = re.sub(r"```.*?```", "", text, flags=re.S)
    text = re.split(r"^## (?:Related pages|See also|Sources)\b", text, flags=re.M)[0]
    return re.sub(r"\]\([^)]*\)", "]", text)


def link_first_use(text, terms):
    """Link the first plain-text use of each glossary term to its entry.

    Skips front matter, headings, tables, code, existing links, quotations and
    the Related/See also/Sources sections. Terms the page already links are left alone.
    Run once with --link-terms; review the diff afterwards.
    """
    fm_match = re.match(r"^---\n.*?\n---\n", text, re.S)
    head = fm_match.group(0) if fm_match else ""
    rest = text[len(head):]
    parts = re.split(r"(^## (?:Related pages|See also|Sources)\b)", rest, maxsplit=1, flags=re.M)
    body, tail = parts[0], "".join(parts[1:])
    lines = body.split("\n")
    in_code = False
    unlinked_text = re.sub(r"<!-- SEEALSO:START -->.*?<!-- SEEALSO:END -->", "", text, flags=re.S)
    for name, anchor, pats in terms:
        if f"{GLOSSARY}#{anchor})" in unlinked_text:
            continue
        done = False
        for i, line in enumerate(lines):
            if line.startswith("```"):
                in_code = not in_code
            if done or in_code or line.startswith(("#", "|", "<!--", "*Disclosure", "[Home]")) or not line.strip():
                continue
            # spans not to touch: links, code, quotations, bold lead sentence markers kept intact
            protected = [m.span() for m in re.finditer(r"\[[^\]]*\]\([^)]*\)|`[^`]*`|\"[^\"]*\"|\*\*", line)]
            for pat in pats:
                for m in re.finditer(pat, line):
                    if any(a <= m.start() < b or a < m.end() <= b for a, b in protected):
                        continue
                    word = m.group(0)
                    lines[i] = f"{line[:m.start()]}[{word}]({GLOSSARY}#{anchor}){line[m.end():]}"
                    done = True
                    break
                if done:
                    break
        in_code = False
    return head + "\n".join(lines) + tail


def main():
    pages = []
    for p in sorted(ROOT.glob("*.md")):
        text = p.read_text(encoding="utf-8")
        meta = front_matter(text)
        if meta.get("category"):
            meta["file"] = p.name
            pages.append(meta)

    pages.sort(key=lambda m: (int(m.get("order", 99)), m["title"]))
    by_cat, by_tag = defaultdict(list), defaultdict(list)
    for m in pages:
        by_cat[m["category"]].append(m)
        for t in m.get("tags", []):
            by_tag[t].append(m)
    cats = sorted_cats(by_cat)

    def item(m):
        desc = f": {m['description']}" if m.get("description") else ""
        return f"- [{m['title']}]({m['file']}){desc}"

    # Sidebar
    side = [GENERATED_NOTE, "", f"**[Home]({HOME})** · [Glossary]({GLOSSARY}) · [Tags](Tags.md)", ""]
    for c in cats:
        side.append(f"**[{c}]({cat_file(c)})**")
        side.append("")
        side += [f"- [{m['title']}]({m['file']})" for m in by_cat[c]]
        side.append("")
    (ROOT / "_Sidebar.md").write_text("\n".join(side), encoding="utf-8")

    # Category pages
    for c in cats:
        lines = [GENERATED_NOTE, "", f"[Home]({HOME}) › Category", "", f"# Category: {c}", "",
                 f"**{len(by_cat[c])} pages in this category.** Other categories: "
                 + ", ".join(f"[{o}]({cat_file(o)})" for o in cats if o != c) + ".", ""]
        lines += [item(m) for m in by_cat[c]]
        lines += ["", "---", "", f"All pages: [Home]({HOME}) · [Tags](Tags.md)", ""]
        (ROOT / cat_file(c)).write_text("\n".join(lines), encoding="utf-8")

    # Tag pages
    for old in ROOT.glob("Tag-*.md"):
        old.unlink()
    for t in sorted(by_tag):
        lines = [GENERATED_NOTE, "", f"[Home]({HOME}) › [Tags](Tags.md)", "", f"# Tag: {t}", ""]
        lines += [f"- [{m['title']}]({m['file']}) ({m['category']})" for m in by_tag[t]]
        lines += [""]
        (ROOT / tag_file(t)).write_text("\n".join(lines), encoding="utf-8")
    tags_index = [GENERATED_NOTE, "", f"[Home]({HOME})", "", "# Tags", "",
                  "Tags describe what a page touches on, across categories. They are added as pages are written, so the list will change.", ""]
    tags_index += [f"- [{t}]({tag_file(t)}) ({len(by_tag[t])})" for t in sorted(by_tag)]
    tags_index.append("")
    (ROOT / "Tags.md").write_text("\n".join(tags_index), encoding="utf-8")

    # Home index
    home = [""]
    for c in cats:
        home += [f"### [{c}]({cat_file(c)})", ""] + [item(m) for m in by_cat[c]] + [""]
    home += ["### Tags", "", " · ".join(f"[{t}]({tag_file(t)})" for t in sorted(by_tag)), ""]
    readme = (ROOT / HOME).read_text(encoding="utf-8")
    (ROOT / HOME).write_text(replace_block(readme, "INDEX", "\n".join(home)), encoding="utf-8")

    # Breadcrumbs and glossary "See also" in content pages
    terms = glossary_terms()
    for m in pages:
        path = ROOT / m["file"]
        text = path.read_text(encoding="utf-8")
        tags = ", ".join(f"[{t}]({tag_file(t)})" for t in m.get("tags", []))
        nav = f"[Home]({HOME}) › [{m['category']}]({cat_file(m['category'])}) · Tags: {tags}"
        text = replace_block(text, "NAV", nav)
        if m["file"] == GLOSSARY:
            see = "- [All pages, by category](_Sidebar.md)\n- [All tags](Tags.md)"
        else:
            body = body_for_terms(text)
            found = [(name, anchor) for name, anchor, pats in terms
                     if any(re.search(p, body) for p in pats)]
            see = "Glossary terms used on this page: " + ", ".join(
                f"[{name}]({GLOSSARY}#{anchor})" for name, anchor in found) + "."
        text = replace_block(text, "SEEALSO", see)
        if "--link-terms" in sys.argv and m["file"] != GLOSSARY:
            text = link_first_use(text, terms)
        path.write_text(text, encoding="utf-8")

    print(f"{len(pages)} pages, {len(cats)} categories, {len(by_tag)} tags.")
    broken = check_links()
    if broken:
        print("Broken relative links:")
        print("\n".join(f"  {b}" for b in broken))
        sys.exit(1)
    print("All relative links resolve.")


def anchors(path):
    text = re.sub(r"```.*?```", "", path.read_text(encoding="utf-8"), flags=re.S)
    return {slug(h) for h in re.findall(r"^#{1,6} (.+)$", text, re.M)}


def check_links():
    broken = []
    for f in sorted(ROOT.glob("*.md")):
        text = re.sub(r"```.*?```", "", f.read_text(encoding="utf-8"), flags=re.S)
        for target in re.findall(r"\]\(([^)\s]+)\)", text):
            if re.match(r"^[a-z]+:", target):
                continue
            path, _, anchor = target.partition("#")
            dest = (f.parent / path).resolve() if path else f
            if not dest.exists():
                broken.append(f"{f.name} -> {target}")
            elif anchor and dest.suffix == ".md" and anchor not in anchors(dest):
                broken.append(f"{f.name} -> {target} (no such heading)")
    return broken


if __name__ == "__main__":
    main()
